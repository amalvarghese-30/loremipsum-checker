CREATE TABLE IF NOT EXISTS `findings` (
  `id` BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  `scan_id` BIGINT UNSIGNED NOT NULL,
  `page_result_id` BIGINT UNSIGNED NOT NULL,
  `resource_id` BIGINT UNSIGNED NULL,
  `page_url` TEXT NOT NULL,
  `resource_url` TEXT NULL,
  `resource_type` VARCHAR(50) NOT NULL DEFAULT 'html',
  `matched_text` TEXT NOT NULL,
  `surrounding_context` TEXT NULL,
  `html_element` VARCHAR(100) NULL,
  `css_selector` VARCHAR(500) NULL,
  `section_name` VARCHAR(500) NULL,
  `line_number` INT UNSIGNED NULL,
  `character_position` INT UNSIGNED NULL,
  `is_visible` TINYINT(1) NULL,
  `detection_rule_id` BIGINT UNSIGNED NULL,
  `detection_category` VARCHAR(100) NOT NULL DEFAULT 'lorem_ipsum',
  `severity` ENUM('high','medium','low') NOT NULL DEFAULT 'high',
  `confidence` ENUM('high','medium','low') NOT NULL DEFAULT 'high',
  `finding_fingerprint` CHAR(64) NOT NULL,
  `created_at` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (`id`),
  INDEX `idx_scan_id` (`scan_id`),
  INDEX `idx_page_result_id` (`page_result_id`),
  INDEX `idx_resource_id` (`resource_id`),
  INDEX `idx_severity` (`severity`),
  INDEX `idx_confidence` (`confidence`),
  INDEX `idx_fingerprint` (`finding_fingerprint`),
  CONSTRAINT `fk_findings_scan` FOREIGN KEY (`scan_id`) REFERENCES `scans`(`id`) ON DELETE CASCADE,
  CONSTRAINT `fk_findings_page_result` FOREIGN KEY (`page_result_id`) REFERENCES `page_results`(`id`) ON DELETE CASCADE,
  CONSTRAINT `fk_findings_resource` FOREIGN KEY (`resource_id`) REFERENCES `scan_resources`(`id`) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
