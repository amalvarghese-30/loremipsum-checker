CREATE TABLE IF NOT EXISTS `scans` (
  `id` BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  `project_id` BIGINT UNSIGNED NOT NULL,
  `scan_number` INT UNSIGNED NOT NULL DEFAULT 1,
  `status` ENUM('queued','initializing','discovering','scanning','pause_requested','paused','cancel_requested','cancelled','completed','failed','interrupted') NOT NULL DEFAULT 'queued',
  `started_at` DATETIME NULL,
  `paused_at` DATETIME NULL,
  `completed_at` DATETIME NULL,
  `last_heartbeat_at` DATETIME NULL,
  `worker_pid` INT NULL,
  `discovered_count` INT UNSIGNED NOT NULL DEFAULT 0,
  `processed_count` INT UNSIGNED NOT NULL DEFAULT 0,
  `clean_count` INT UNSIGNED NOT NULL DEFAULT 0,
  `affected_page_count` INT UNSIGNED NOT NULL DEFAULT 0,
  `failed_count` INT UNSIGNED NOT NULL DEFAULT 0,
  `total_findings` INT UNSIGNED NOT NULL DEFAULT 0,
  `elapsed_time` INT UNSIGNED NULL COMMENT 'seconds',
  `error_message` TEXT NULL,
  `created_at` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  `updated_at` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (`id`),
  INDEX `idx_project_id` (`project_id`),
  INDEX `idx_status` (`status`),
  INDEX `idx_last_heartbeat` (`last_heartbeat_at`),
  CONSTRAINT `fk_scans_project` FOREIGN KEY (`project_id`) REFERENCES `projects`(`id`) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
