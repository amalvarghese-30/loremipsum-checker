CREATE TABLE IF NOT EXISTS `scan_resources` (
  `id` BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  `scan_id` BIGINT UNSIGNED NOT NULL,
  `page_result_id` BIGINT UNSIGNED NULL,
  `resource_url` TEXT NOT NULL,
  `normalized_resource_url` VARCHAR(2048) NOT NULL,
  `resource_hash` CHAR(64) NOT NULL,
  `resource_type` ENUM('javascript','css','json','xml','text','other') NOT NULL DEFAULT 'other',
  `content_type` VARCHAR(255) NULL,
  `http_status` SMALLINT NULL,
  `processing_status` ENUM('pending','completed','failed','skipped') NOT NULL DEFAULT 'pending',
  `response_size` INT UNSIGNED NULL,
  `duration_ms` INT UNSIGNED NULL,
  `finding_count` INT UNSIGNED NOT NULL DEFAULT 0,
  `error_message` TEXT NULL,
  `fetched_at` DATETIME NULL,
  PRIMARY KEY (`id`),
  UNIQUE KEY `uq_scan_resource_hash` (`scan_id`, `resource_hash`),
  INDEX `idx_scan_id` (`scan_id`),
  INDEX `idx_page_result_id` (`page_result_id`),
  INDEX `idx_resource_type` (`resource_type`),
  CONSTRAINT `fk_sr_scan` FOREIGN KEY (`scan_id`) REFERENCES `scans`(`id`) ON DELETE CASCADE,
  CONSTRAINT `fk_sr_page_result` FOREIGN KEY (`page_result_id`) REFERENCES `page_results`(`id`) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
