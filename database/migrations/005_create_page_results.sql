CREATE TABLE IF NOT EXISTS `page_results` (
  `id` BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  `scan_id` BIGINT UNSIGNED NOT NULL,
  `discovered_url_id` BIGINT UNSIGNED NOT NULL,
  `requested_url` TEXT NOT NULL,
  `final_url` TEXT NULL,
  `http_status` SMALLINT NULL,
  `content_type` VARCHAR(255) NULL,
  `processing_status` ENUM('clean','findings_detected','failed','needs_review','cloudflare_blocked','bot_blocked') NOT NULL DEFAULT 'clean',
  `finding_count` INT UNSIGNED NOT NULL DEFAULT 0,
  `duration_ms` INT UNSIGNED NULL,
  `retry_count` TINYINT UNSIGNED NOT NULL DEFAULT 0,
  `error_type` VARCHAR(100) NULL,
  `error_message` TEXT NULL,
  `page_title` VARCHAR(1000) NULL,
  `word_count` INT UNSIGNED NULL,
  `has_lorem_ipsum` TINYINT(1) NOT NULL DEFAULT 0,
  `started_at` DATETIME NULL,
  `completed_at` DATETIME NULL,
  PRIMARY KEY (`id`),
  INDEX `idx_scan_id` (`scan_id`),
  INDEX `idx_discovered_url_id` (`discovered_url_id`),
  INDEX `idx_processing_status` (`processing_status`),
  INDEX `idx_has_lorem_ipsum` (`has_lorem_ipsum`),
  CONSTRAINT `fk_pr_scan` FOREIGN KEY (`scan_id`) REFERENCES `scans`(`id`) ON DELETE CASCADE,
  CONSTRAINT `fk_pr_discovered_url` FOREIGN KEY (`discovered_url_id`) REFERENCES `discovered_urls`(`id`) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
